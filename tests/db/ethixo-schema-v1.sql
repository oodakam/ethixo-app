-- profiles: SELECT own or (teacher) own-class students | INSERT none (RPC) | UPDATE own display_name/level | DELETE none
create policy profiles_select_own     on public.profiles for select to authenticated using (id = (select auth.uid()));
create policy profiles_select_teacher on public.profiles for select to authenticated using (private.teaches_student(id));
create policy profiles_update_own     on public.profiles for update to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));

-- classes: SELECT teacher own / student member | INSERT approved teacher, own | UPDATE none | DELETE none
create policy classes_select_teacher on public.classes for select to authenticated using (teacher_id = (select auth.uid()) and private.is_approved_teacher());
create policy classes_select_student on public.classes for select to authenticated using (private.in_class(id));
create policy classes_insert_teacher on public.classes for insert to authenticated
  with check (teacher_id = (select auth.uid()) and private.is_approved_teacher());

-- class_members: SELECT student own / teacher of that class | INSERT none (join_class RPC) | UPDATE none | DELETE none
create policy members_select_student on public.class_members for select to authenticated using (student_id = (select auth.uid()));
create policy members_select_teacher on public.class_members for select to authenticated using (private.teaches_class(class_id));

-- attempts: student full own (no delete). Teacher: NO direct access (uses teacher_attempt_summary).
create policy attempts_select_own on public.attempts for select to authenticated using (student_id = (select auth.uid()) and private.is_student());
create policy attempts_insert_own on public.attempts for insert to authenticated with check (student_id = (select auth.uid()) and private.is_student());
create policy attempts_update_own on public.attempts for update to authenticated
  using (student_id = (select auth.uid()) and private.is_student()) with check (student_id = (select auth.uid()) and private.is_student());
-- Defence in depth: even if a permissive policy is added by mistake later, only the owner can ever pass.
create policy attempts_owner_only on public.attempts as restrictive for all to authenticated using (student_id = (select auth.uid()));

-- vault_entries: student full own (delete needed: students remove saved answers). Teacher: NOTHING.
create policy vault_select_own on public.vault_entries for select to authenticated using (student_id = (select auth.uid()) and private.is_student());
create policy vault_insert_own on public.vault_entries for insert to authenticated with check (student_id = (select auth.uid()) and private.is_student());
create policy vault_update_own on public.vault_entries for update to authenticated
  using (student_id = (select auth.uid()) and private.is_student()) with check (student_id = (select auth.uid()) and private.is_student());
create policy vault_delete_own on public.vault_entries for delete to authenticated using (student_id = (select auth.uid()) and private.is_student());
create policy vault_owner_only on public.vault_entries as restrictive for all to authenticated using (student_id = (select auth.uid()));

-- assignments: SELECT teacher own / student in that class | INSERT approved teacher for own class | UPDATE none | DELETE none
create policy assignments_select_teacher on public.assignments for select to authenticated
  using (teacher_id = (select auth.uid()) and private.is_approved_teacher());
create policy assignments_select_student on public.assignments for select to authenticated using (private.in_class(class_id));
create policy assignments_insert_teacher on public.assignments for insert to authenticated
  with check (teacher_id = (select auth.uid()) and private.teaches_class(class_id));

-- student_state: student own | teacher none
create policy state_select_own on public.student_state for select to authenticated using (student_id = (select auth.uid()) and private.is_student());
create policy state_insert_own on public.student_state for insert to authenticated with check (student_id = (select auth.uid()) and private.is_student());
create policy state_update_own on public.student_state for update to authenticated
  using (student_id = (select auth.uid()) and private.is_student()) with check (student_id = (select auth.uid()) and private.is_student());

