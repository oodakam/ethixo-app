-- =====================================================================
-- Ethixo MVP database schema v1  (hardened)   -- DRAFT FOR REVIEW
-- Supabase / Postgres, region: Singapore (ap-southeast-1)
-- Same 7 tables, same JSONB approach as v0. Nothing here has been run on Supabase.
--
-- Design rules
--  R1  Clients get ONLY the privileges Ethixo needs (table + column level GRANTs),
--      and RLS decides which ROWS. Supabase grants broad defaults, so we revoke first.
--  R2  Identity / ownership columns (id, student_id, teacher_id, role, join_code) are
--      never client-writable after creation.
--  R3  Anything that must be validated (profile creation, class join) happens in a
--      SECURITY DEFINER function. No service_role key is ever needed on the client.
--  R4  Teachers never read vault_entries. Teachers never read raw attempt answers;
--      they read an aggregated summary (see teacher_attempt_summary).
-- Note: anonymous Supabase users use the Postgres role "authenticated", so student vs
-- teacher is decided from public.profiles.role, never from the Postgres role.
-- =====================================================================

-- ---------- 0. Lock down default privileges ---------------------------------
alter default privileges for role postgres in schema public revoke all on tables    from anon, authenticated;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated;
alter default privileges for role postgres in schema public revoke execute on functions from public, anon, authenticated;

-- Private schema for RLS helper functions: not exposed through the API.
create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;
alter default privileges for role postgres in schema private revoke execute on functions from public, anon, authenticated;

-- ---------- 1. Tables ---------------------------------------------------------
create table public.profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  role         text not null check (role in ('student','teacher')),
  display_name text not null check (char_length(btrim(display_name)) between 1 and 40),
  level        text check (level is null or char_length(level) <= 10),
  is_approved  boolean not null default false,   -- teachers need manual approval; students are set true
  created_at   timestamptz not null default now(),
  constraint teacher_has_no_level check (role = 'student' or level is null)
);

create table public.classes (
  id         uuid primary key default gen_random_uuid(),
  teacher_id uuid not null default auth.uid() references public.profiles(id),
  name       text not null check (char_length(btrim(name)) between 1 and 40),
  -- 10 hex chars (40 bits) from a cryptographically random UUID; generated by the DB, never by the client
  join_code  text not null unique default upper(substr(replace(gen_random_uuid()::text,'-',''),1,10)),
  created_at timestamptz not null default now(),
  unique (id, teacher_id)                         -- target for the composite FK from assignments
);

create table public.class_members (
  class_id   uuid not null references public.classes(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  joined_at  timestamptz not null default now(),
  primary key (class_id, student_id)
);
create index class_members_student_idx on public.class_members(student_id);

-- One row per question; data = the same ARRAY of attempt objects the app stores today
-- under localStorage key "attempts:{level}:{subject}:{lesson}:{idx}".
create table public.attempts (
  id          uuid primary key default gen_random_uuid(),
  student_id  uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  level       text not null check (char_length(level) between 1 and 10),
  subject_key text not null check (char_length(subject_key) between 1 and 40),
  lesson_id   text not null check (char_length(lesson_id) between 1 and 40),
  q_idx       int  not null check (q_idx between 0 and 999),
  data        jsonb not null check (jsonb_typeof(data) = 'array' and pg_column_size(data) <= 200000),
  updated_at  timestamptz not null default now(),
  unique (student_id, level, subject_key, lesson_id, q_idx)
);

-- One row per saved answer; data = the same entry object the app stores today in the "vault" array.
create table public.vault_entries (
  id          uuid primary key default gen_random_uuid(),
  student_id  uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  qid         text not null check (char_length(qid) between 1 and 200),   -- the app's v.qid
  subject_key text check (subject_key is null or char_length(subject_key) <= 40),
  lesson_id   text check (lesson_id is null or char_length(lesson_id) <= 40),
  data        jsonb not null check (jsonb_typeof(data) = 'object' and pg_column_size(data) <= 100000),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (student_id, qid)
);

create table public.assignments (
  id          uuid primary key default gen_random_uuid(),
  class_id    uuid not null,
  teacher_id  uuid not null default auth.uid(),
  level       text not null check (char_length(level) between 1 and 10),
  subject_key text not null check (char_length(subject_key) between 1 and 40),
  lesson_id   text not null check (char_length(lesson_id) between 1 and 40),
  due_date    date,
  created_at  timestamptz not null default now(),
  -- DATABASE-LEVEL guarantee: the (class, teacher) pair must exist in classes.
  -- A teacher can never own an assignment for a class that belongs to someone else.
  foreign key (class_id, teacher_id) references public.classes(id, teacher_id) on delete cascade
);
create index assignments_class_idx on public.assignments(class_id);

-- Replaces lastLesson, chosenLevel, timelog, lastActive (object keyed by those names).
create table public.student_state (
  student_id uuid primary key default auth.uid() references public.profiles(id) on delete cascade,
  data       jsonb not null default '{}'::jsonb check (jsonb_typeof(data) = 'object' and pg_column_size(data) <= 200000),
  updated_at timestamptz not null default now()
);

-- updated_at is maintained by the database, not trusted from the client
create function private.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
create trigger attempts_touch      before update on public.attempts      for each row execute function private.touch_updated_at();
create trigger vault_touch         before update on public.vault_entries for each row execute function private.touch_updated_at();
create trigger student_state_touch before update on public.student_state for each row execute function private.touch_updated_at();

-- ---------- 2. RLS helper functions (SECURITY DEFINER, private schema) --------
-- They bypass RLS on purpose, so policies can look across tables without infinite recursion.
-- They only ever answer yes/no about auth.uid(); they never return another user's rows.
create function private.is_student() returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'student') $$;

create function private.is_approved_teacher() returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles p
                 where p.id = (select auth.uid()) and p.role = 'teacher' and p.is_approved) $$;

create function private.teaches_class(cid uuid) returns boolean language sql stable security definer set search_path = '' as $$
  select private.is_approved_teacher()
     and exists (select 1 from public.classes c where c.id = cid and c.teacher_id = (select auth.uid())) $$;

create function private.in_class(cid uuid) returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.class_members m where m.class_id = cid and m.student_id = (select auth.uid())) $$;

create function private.teaches_student(sid uuid) returns boolean language sql stable security definer set search_path = '' as $$
  select private.is_approved_teacher()
     and exists (select 1 from public.class_members m join public.classes c on c.id = m.class_id
                 where m.student_id = sid and c.teacher_id = (select auth.uid())) $$;

grant execute on function private.is_student(), private.is_approved_teacher(), private.teaches_class(uuid),
                          private.in_class(uuid), private.teaches_student(uuid) to authenticated;

-- ---------- 3. Public RPCs (the only way to create profiles / join classes) ---
create function public.create_my_profile(p_role text, p_display_name text, p_level text default null)
returns public.profiles language plpgsql security definer set search_path = '' as $$
declare
  v_uid  uuid    := auth.uid();
  v_anon boolean := coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false);
  r public.profiles;
begin
  if v_uid is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  if p_role not in ('student','teacher') then raise exception 'invalid role' using errcode = '22023'; end if;
  if p_role = 'teacher' and v_anon then raise exception 'teachers must sign in with email' using errcode = '42501'; end if;
  if exists (select 1 from public.profiles where id = v_uid) then raise exception 'profile already exists' using errcode = '23505'; end if;
  insert into public.profiles (id, role, display_name, level, is_approved)
  values (v_uid, p_role, btrim(p_display_name), case when p_role = 'student' then p_level end, p_role = 'student')
  returning * into r;
  return r;
end $$;

create function public.join_class(p_code text)
returns table (class_id uuid, class_name text) language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid(); v_class public.classes;
begin
  if v_uid is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  if not private.is_student() then raise exception 'only students can join a class' using errcode = '42501'; end if;
  select * into v_class from public.classes where join_code = upper(btrim(p_code));
  if not found then raise exception 'invalid class code' using errcode = 'P0002'; end if;
  insert into public.class_members (class_id, student_id) values (v_class.id, v_uid) on conflict do nothing;
  return query select v_class.id, v_class.name;
end $$;

-- Teacher progress data WITHOUT the student's raw answers / feedback text (Practice Privacy).
-- Fields are exactly what the evidence-gated dashboard needs: counts, scores, timestamps, thinking-used.
create function public.teacher_attempt_summary(p_class_id uuid default null)
returns table (student_id uuid, display_name text, class_id uuid, level text, subject_key text, lesson_id text,
               q_idx int, attempt_count int, latest_at numeric, latest_score numeric, best_score numeric, used_thinking boolean)
language sql stable security definer set search_path = '' as $$
  select a.student_id, p.display_name, c.id, a.level, a.subject_key, a.lesson_id, a.q_idx,
         s.cnt, s.latest_at, s.latest_score, s.best_score, s.used
  from public.attempts a
  join public.class_members m on m.student_id = a.student_id
  join public.classes c       on c.id = m.class_id and c.teacher_id = (select auth.uid())
  join public.profiles p      on p.id = a.student_id
  cross join lateral (
    select count(*)::int                                  as cnt,
           max((e ->> 'at')::numeric)                     as latest_at,
           max((e ->> 'score')::numeric)                  as best_score,
           bool_or(coalesce((e ->> 'usedThinking')::boolean, false)) as used,
           (array_agg((e ->> 'score')::numeric order by (e ->> 'at')::numeric desc nulls last))[1] as latest_score
    from jsonb_array_elements(a.data) e) s
  where private.is_approved_teacher()
    and (p_class_id is null or c.id = p_class_id) $$;

revoke all on function public.create_my_profile(text,text,text), public.join_class(text),
                       public.teacher_attempt_summary(uuid) from public, anon;
grant execute on function public.create_my_profile(text,text,text), public.join_class(text),
                          public.teacher_attempt_summary(uuid) to authenticated;

